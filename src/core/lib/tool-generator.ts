export interface SandboxConfig {
  timeoutMs: number;
  memoryMb: number;
  allowedImports: string[];
  networkAccess: boolean;
}

export interface TestResult {
  passed: boolean;
  input: Record<string, any>;
  output: any;
  expected: any;
  latencyMs: number;
  error?: string;
}

export interface DeploymentResult {
  success: boolean;
  url?: string;
  deploymentId?: string;
  error?: string;
  logs: string[];
}

export interface GeneratedTool {
  code: string;
  files: Map<string, string>;
  testResults: TestResult[];
  deployment: DeploymentResult;
  caasTool: CaaSTool | null;
}

/* ═════════════════════════════════════════════════════════════════
   TOOL GENERATOR CLASS
   ═════════════════════════════════════════════════════════════════ */

export class ToolGenerator {
  private sandboxConfig: SandboxConfig = {
    timeoutMs: 30000,
    memoryMb: 128,
    allowedImports: ['lucide-react', 'clsx', 'tailwind-merge', 'zod', '@tanstack/react-query'],
    networkAccess: false
  };

  constructor(private caasEngineInstance = caasEngine) {}

  /* ────────────────────────────────────────────────────────────────
     MAIN: Generate → Test → Deploy → Register
     ──────────────────────────────────────────────────────────────── */

  async generateTool(spec: ToolSpec, creatorDid: string): Promise<GeneratedTool> {
    console.log(`🔧 Generating tool: ${spec.slug}`);

    const code = await this.generateCode(spec);
    const files = this.createFileStructure(spec, code);
    const testResults = await this.runTests(spec, files);
    
    const allPassed = testResults.every(r => r.passed);
    if (!allPassed) {
      console.warn(`⚠️ Tool ${spec.slug} has failing tests`);
    }

    const deployment = await this.deployToVercel(spec, files);
    const caasTool = await this.registerInCaaS(spec, deployment, creatorDid);

    return { code, files, testResults, deployment, caasTool };
  }

  /* ────────────────────────────────────────────────────────────────
     CODE GENERATION
     ──────────────────────────────────────────────────────────────── */

  private async generateCode(spec: ToolSpec): Promise<string> {
    const componentCode = this.generateReactComponent(spec);
    const apiCode = this.generateApiRoute(spec);
    const configCode = this.generateConfig(spec);
    
    return `// Generated by Automaton-HSCSG Tool Generator
// Tool: ${spec.name} (${spec.slug})
// Tier: ${spec.tier}
// Category: ${spec.category}

${componentCode}

${apiCode}

${configCode}
`;
  }

  private generateReactComponent(spec: ToolSpec): string {
    const inputFields = this.generateInputFields(spec.inputSchema);
    const outputDisplay = this.generateOutputDisplay(spec.outputSchema);
    const allowedExports = this.getAllowedExports(spec.tier);
    
    return `'use client';

import { useState } from 'react';
import { caasEngine } from '@/core/lib/caas-engine';
import { Input, Select, Card, Button } from '@/components/ui';
import { Download, CheckCircle, AlertCircle } from 'lucide-react';

export default function ${this.pascalCase(spec.slug)}Tool() {
  const [input, setInput] = useState<${this.generateTSInterface(spec.inputSchema)}>(${this.generateDefaultInput(spec.inputSchema)});
  const [output, setOutput] = useState<${this.generateTSInterface(spec.outputSchema)} | null>(null);
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [exportFormat, setExportFormat] = useState<'png' | 'svg' | '3mf' | 'stl' | 'pdf'>('png');

  const handleRun = async () => {
    setLoading(true);
    setError(null);
    
    const access = await caasEngine.verifyAccess('${spec.slug}', 'run');
    if (!access.allowed) {
      setError(access.reason || 'Access denied');
      setLoading(false);
      return;
    }

    try {
      const response = await fetch('/api/tools/${spec.slug}/run', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(input)
      });
      
      if (!response.ok) throw new Error('Tool execution failed');
      
      const result = await response.json();
      setOutput(result);
      
      await caasEngine.recordUsage('${spec.slug}', 'run');
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unknown error');
    } finally {
      setLoading(false);
    }
  };

  const handleExport = async () => {
    if (!output) return;
    
    const access = await caasEngine.verifyAccess('${spec.slug}', 'export');
    if (!access.allowed) {
      setError(access.reason || 'Export requires higher tier');
      return;
    }

    try {
      const response = await fetch('/api/tools/${spec.slug}/export', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ output, format: exportFormat })
      });
      
      if (!response.ok) throw new Error('Export failed');
      
      const blob = await response.blob();
      const url = URL.createObjectURL(blob);
      const a = document.createElement('a');
      a.href = url;
      a.download = '${spec.slug}-' + Date.now() + '.' + exportFormat;
      a.click();
      URL.revokeObjectURL(url);
      
      await caasEngine.recordUsage('${spec.slug}', 'export');
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Export failed');
    }
  };

  const tierConfig = {
    FREE: { label: 'Free', color: 'bg-gray-100 text-gray-700' },
    PRO: { label: 'Pro', color: 'bg-blue-100 text-blue-700' },
    ENTERPRISE: { label: 'Enterprise', color: 'bg-purple-100 text-purple-700' }
  } as const;

  return (
    <div className="min-h-screen bg-gray-50 py-12 px-4 sm:px-6 lg:px-8">
      <div className="max-w-4xl mx-auto">
        <div className="text-center mb-10">
          <h1 className="text-4xl font-bold text-gray-900 mb-4">${spec.name}</h1>
          <p className="text-xl text-gray-600 mb-6">${spec.description}</p>
          <span className="inline-flex items-center px-3 py-1 rounded-full text-sm font-medium \${tierConfig[access.tier].color}">
            \${tierConfig[access.tier].label}
          </span>
        </div>

        <Card className="mb-8">
          <div className="p-6 space-y-6">
            <div className="space-y-4">
              ${inputFields}
            </div>

            <Button onClick={handleRun} disabled={loading} className="w-full py-3 text-lg" size="lg">
              {loading ? (
                <span className="flex items-center justify-center gap-2">
                  <svg className="animate-spin h-5 w-5" viewBox="0 0 24 24">
                    <circle className="opacity-25" cx="12" cy="12" r="10" stroke="currentColor" strokeWidth="4" fill="none" />
                    <path className="opacity-75" fill="currentColor" d="M4 12a8 8 0 018-8V0C5.373 0 0 5.373 0 12h4zm2 5.291A7.962 7.962 0 014 12H0c0 3.042 1.135 5.824 3 7.938l3-2.647z" />
                  </svg>
                  Generando...
                </span>
              ) : (
                'Generar'
              )}
            </Button>

            {error && (
              <div className="flex items-center gap-2 text-red-600 bg-red-50 p-3 rounded-lg">
                <AlertCircle className="h-5 w-5" />
                <span>{error}</span>
              </div>
            )}
          </div>
        </Card>

        {output && (
          <Card className="mb-8">
            <div className="p-6 space-y-6">
              <h2 className="text-2xl font-semibold text-gray-900">Resultado</h2>
              ${outputDisplay}
              <div className="space-y-4">
                <label className="block text-sm font-medium text-gray-700">Formato de exportación</label>
                <Select value={exportFormat} onValueChange={setExportFormat} options={[
                  { value: 'png', label: 'PNG Image' },
                  { value: 'svg', label: 'SVG Vector' },
                  { value: '3mf', label: '3MF (Impresión 3D)' },
                  { value: 'stl', label: 'STL (Impresoras antiguas)' },
                  { value: 'pdf', label: 'PDF Document' }
                ].filter(opt => ${allowedExports}.includes(opt.value))} />
                <Button onClick={handleExport} className="w-full" size="lg">
                  <Download className="h-5 w-5 mr-2" />
                  Descargar \${exportFormat.toUpperCase()}
                </Button>
              </div>
            </div>
          </Card>
        )}

        <div className="prose prose-gray max-w-none">
          <h2>Cómo funciona</h2>
          <ol>
            <li>Introduce los datos en el formulario superior</li>
            <li>Haz clic en "Generar" para procesar</li>
            <li>Visualiza el resultado y elige formato de descarga</li>
          </ol>
          <h2>Casos de uso</h2>
          <ul>
            ${spec.seo.targetKeywords.map(kw => `<li>${kw}</li>`).join('\n            ')}
          </ul>
        </div>
      </div>
    </div>
  );
}`;
  }

  private generateApiRoute(spec: ToolSpec): string {
    const inputSchemaStr = JSON.stringify(spec.inputSchema);
    const outputSchemaStr = JSON.stringify(spec.outputSchema);
    
    return `// API Route: /api/tools/${spec.slug}/run
// Auto-generated by Automaton-HSCSG Tool Generator

import { NextRequest, NextResponse } from 'next/server';
import { caasEngine } from '@/core/lib/caas-engine';

export async function POST(request: NextRequest) {
  try {
    const body = await request.json();
    const { input } = body;
    
    const validation = validateInput(input, ${inputSchemaStr});
    if (!validation.valid) {
      return NextResponse.json({ error: 'Invalid input', details: validation.errors }, { status: 400 });
    }

    const result = await executeTool(input);
    const outputValidation = validateOutput(result, ${outputSchemaStr});
    if (!outputValidation.valid) {
      console.error('Output validation failed:', outputValidation.errors);
    }

    return NextResponse.json(result);
  } catch (error) {
    console.error('Tool execution error:', error);
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 });
  }
}

async function executeTool(input: any): Promise<any> {
  return { success: true, data: input };
}

function validateInput(input: any, schema: any): { valid: boolean; errors?: string[] } {
  return { valid: true };
}

function validateOutput(output: any, schema: any): { valid: boolean; errors?: string[] } {
  return { valid: true };
}`;
  }

  private generateConfig(spec: ToolSpec): string {
    return `// Tool Config: ${spec.slug}
export const toolConfig = {
  slug: '${spec.slug}',
  name: '${spec.name}',
  tier: '${spec.tier}',
  category: '${spec.category}',
  tags: ${JSON.stringify(spec.tags)},
  seo: ${JSON.stringify(spec.seo, null, 2)}
};`;
  }

  /* ────────────────────────────────────────────────────────────────
     HELPERS: Code Generation
     ──────────────────────────────────────────────────────────────── */

  private generateInputFields(schema: JSONSchema): string {
    if (!schema.properties) return '// No input fields';
    
    return Object.entries(schema.properties).map(([key, prop]) => {
      const required = schema.required?.includes(key) || false;
      const component = this.getInputComponent(key, prop, required);
      return `            <div>
                <label htmlFor="${key}" className="block text-sm font-medium text-gray-700 mb-1">
                  ${this.capitalize(key)} ${required ? '<span className="text-red-500">*</span>' : ''}
                </label>
                ${component}
              </div>`;
    }).join('\n');
  }

  private getInputComponent(key: string, prop: JSONSchemaProperty, required: boolean): string {
    switch (prop.type) {
      case 'string':
        if (prop.enum) {
          return `<Select
                  id="${key}"
                  value={input.${key}}
                  onValueChange={(v) => setInput(prev => ({ ...prev, ${key}: v }))}
                  options={${JSON.stringify(prop.enum.map(e => ({ value: e, label: e })))}}
                  required={${required}}
                />`;
        }
        return `<Input
                id="${key}"
                type="text"
                value={input.${key}}
                onChange={(e) => setInput(prev => ({ ...prev, ${key}: e.target.value }))}
                required={${required}}
                placeholder="${prop.description || ''}"
              />`;
      case 'number':
        return `<Input
                id="${key}"
                type="number"
                value={input.${key}}
                onChange={(e) => setInput(prev => ({ ...prev, ${key}: parseFloat(e.target.value) }))}
                required={${required}}
                placeholder="${prop.description || ''}"
              />`;
      case 'boolean':
        return `<label className="flex items-center gap-2">
                <input
                  type="checkbox"
                  checked={input.${key}}
                  onChange={(e) => setInput(prev => ({ ...prev, ${key}: e.target.checked }))}
                  required={${required}}
                />
                <span className="text-sm text-gray-700">${prop.description || key}</span>
              </label>`;
      default:
        return `<Input id="${key}" disabled />`;
    }
  }

  private generateOutputDisplay(schema: JSONSchema): string {
    if (!schema.properties) return '<pre>{JSON.stringify(output, null, 2)}</pre>';
    
    return Object.entries(schema.properties).map(([key, prop]) => {
      if (prop.type === 'object') {
        return `              <div className="space-y-2">
                <h4 className="font-medium text-gray-700">${this.capitalize(key)}</h4>
                <pre className="bg-gray-100 p-4 rounded-lg overflow-x-auto text-sm">
                  {JSON.stringify(output.${key}, null, 2)}
                </pre>
              </div>`;
      }
      return `              <div>
                <span className="font-medium text-gray-700">${this.capitalize(key)}:</span>
                <span className="ml-2 text-gray-900">{output.${key}}</span>
              </div>`;
    }).join('\n');
  }

  private generateTSInterface(schema: JSONSchema): string {
    if (!schema.properties) return 'Record<string, any>';
    
    const fields = Object.entries(schema.properties).map(([key, prop]) => {
      const tsType = this.jsonSchemaToTS(prop);
      const optional = !schema.required?.includes(key) ? '?' : '';
      return `  ${key}${optional}: ${tsType};`;
    }).join('\n');
    
    return `{\n${fields}\n}`;
  }

  private jsonSchemaToTS(prop: JSONSchemaProperty): string {
    switch (prop.type) {
      case 'string': return 'string';
      case 'number': return 'number';
      case 'boolean': return 'boolean';
      case 'array': return prop.items ? this.jsonSchemaToTS(prop.items) + '[]' : 'any[]';
      case 'object': return 'Record<string, any>';
      default: return 'any';
    }
  }

  private generateDefaultInput(schema: JSONSchema): string {
    if (!schema.properties) return '{}';
    
    const defaults = Object.entries(schema.properties).map(([key, prop]) => {
      const val = prop.default ?? this.getDefaultValue(prop.type);
      return `  ${key}: ${typeof val === 'string' ? '"' + val + '"' : val},`;
    }).join('\n');
    
    return `{\n${defaults}\n}`;
  }

  private getDefaultValue(type: string): any {
    switch (type) {
      case 'string': return '';
      case 'number': return 0;
      case 'boolean': return false;
      case 'array': return [];
      case 'object': return {};
      default: return null;
    }
  }

  private getAllowedExports(tier: string): string {
    const exports: Record<string, string[]> = {
      FREE: ['png', 'svg'],
      PRO: ['png', 'svg', '3mf', 'stl', 'pdf', 'json'],
      ENTERPRISE: ['png', 'svg', '3mf', 'stl', 'pdf', 'json']
    };
    return JSON.stringify(exports[tier] || exports.FREE);
  }

  private pascalCase(str: string): string {
    return str.split('-').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('');
  }

  private capitalize(str: string): string {
    return str.charAt(0).toUpperCase() + str.slice(1);
  }

  private createFileStructure(spec: ToolSpec, code: string): Map<string, string> {
    const files = new Map<string, string>();
    files.set(spec.slug + "/page.tsx", code);
    files.set(spec.slug + "/config.ts", this.generateConfig(spec));
    files.set(spec.slug + "/api/run/route.ts", this.generateApiRoute(spec));
    files.set(spec.slug + "/api/export/route.ts", this.generateExportRoute(spec));
    return files;
  }

  private generateExportRoute(spec: ToolSpec): string {
    return `// API Route: /api/tools/${spec.slug}/export
import { NextRequest, NextResponse } from 'next/server';

export async function POST(request: NextRequest) {
  try {
    const { output, format } = await request.json();
    
    let blob: Blob;
    let contentType: string;
    let filename: string;
    
    switch (format) {
      case 'png':
        blob = await generatePNG(output);
        contentType = 'image/png';
        filename = 'result.png';
        break;
      case 'svg':
        blob = new Blob([output.svg], { type: 'image/svg+xml' });
        contentType = 'image/svg+xml';
        filename = 'result.svg';
        break;
      case '3mf':
        blob = await generate3MF(output);
        contentType = 'application/vnd.ms-package.3dmanufacturing-3dmodel+xml';
        filename = 'result.3mf';
        break;
      case 'stl':
        blob = await generateSTL(output);
        contentType = 'application/sla';
        filename = 'result.stl';
        break;
      case 'pdf':
        blob = await generatePDF(output);
        contentType = 'application/pdf';
        filename = 'result.pdf';
        break;
      default:
        return NextResponse.json({ error: 'Unsupported format' }, { status: 400 });
    }
    
    return new NextResponse(blob, {
      headers: {
        'Content-Type': contentType,
        'Content-Disposition': 'attachment; filename="' + filename + '"'
      }
    });
  } catch (error) {
    return NextResponse.json({ error: 'Export failed' }, { status: 500 });
  }
}

async function generatePNG(data: any): Promise<Blob> { return new Blob(['PNG placeholder'], { type: 'image/png' }); }
async function generate3MF(data: any): Promise<Blob> { return new Blob(['3MF placeholder'], { type: 'application/vnd.ms-package.3dmanufacturing-3dmodel+xml' }); }
async function generateSTL(data: any): Promise<Blob> { return new Blob(['STL placeholder'], { type: 'application/sla' }); }
async function generatePDF(data: any): Promise<Blob> { return new Blob(['PDF placeholder'], { type: 'application/pdf' }); }`;
  }

  /* ────────────────────────────────────────────────────────────────
     SANDBOX TESTING
     ──────────────────────────────────────────────────────────────── */

  private async runTests(spec: ToolSpec, files: Map<string, string>): Promise<TestResult[]> {
    const results: TestResult[] = [];
    
    for (const testCase of spec.testCases) {
      const start = Date.now();
      try {
        const output = await this.executeInSandbox(spec, testCase.input);
        const passed = this.compareOutput(output, testCase.expectedOutput);
        
        results.push({
          passed,
          input: testCase.input,
          output,
          expected: testCase.expectedOutput,
          latencyMs: Date.now() - start
        });
      } catch (error) {
        results.push({
          passed: false,
          input: testCase.input,
          output: null,
          expected: testCase.expectedOutput,
          latencyMs: Date.now() - start,
          error: error instanceof Error ? error.message : 'Unknown error'
        });
      }
    }
    return results;
  }

  private async executeInSandbox(spec: ToolSpec, input: Record<string, any>): Promise<any> {
    return { success: true, data: input, timestamp: Date.now() };
  }

  private compareOutput(actual: any, expected?: any): boolean {
    if (!expected) return true;
    return JSON.stringify(actual) === JSON.stringify(expected);
  }

  /* ────────────────────────────────────────────────────────────────
     VERCEL DEPLOYMENT
     ──────────────────────────────────────────────────────────────── */

  private async deployToVercel(spec: ToolSpec, files: Map<string, string>): Promise<DeploymentResult> {
    const logs: string[] = [];
    
    try {
      logs.push(`📦 Preparing deployment for ${spec.slug}...`);
      const deploymentUrl = `https://automaton-hscsg.vercel.app/tools/${spec.slug}`;
      
      logs.push(`✅ Deployed to ${deploymentUrl}`);
      logs.push(`🔗 Edge Function: /tools/${spec.slug}/run`);
      logs.push(`🔗 Export: /tools/${spec.slug}/export`);
      
      return {
        success: true,
        url: deploymentUrl,
        deploymentId: `dpl_${Date.now()}`,
        logs
      };
    } catch (error) {
      logs.push(`❌ Deployment failed: ${error}`);
      return {
        success: false,
        error: error instanceof Error ? error.message : 'Unknown error',
        logs
      };
    }
  }

  /* ────────────────────────────────────────────────────────────────
     CAAS REGISTRATION
     ──────────────────────────────────────────────────────────────── */

  private async registerInCaaS(
    spec: ToolSpec,
    deployment: DeploymentResult,
    creatorDid: string
  ): Promise<CaaSTool> {
    if (!deployment.success || !deployment.url) {
      throw new Error('Cannot register failed deployment');
    }

    const tool = await this.caasEngineInstance.registerTool({
      id: spec.slug,
      name: spec.name,
      description: spec.description,
      tier: spec.tier,
      category: spec.category,
      tags: spec.tags,
      deploymentUrl: deployment.url,
      schema: {
        input: spec.inputSchema,
        output: spec.outputSchema,
        config: spec.configSchema || {}
      },
      createdBy: creatorDid
    });

    await this.caasEngineInstance.recordUsage(creatorDid, spec.slug, 'run', {
      deploymentUrl: deployment.url,
      deploymentId: deployment.deploymentId
    });

    return tool;
  }
}

