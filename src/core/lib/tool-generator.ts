/* ═══════════════════════════════════════════════════════════════════
   BATCH GENERATION (LoopEngine Integration)
   ══════════════════════════════════════════════════════════════════ */

export async function batchGenerateTools(
  specs: ToolSpec[],
  creatorDid: string
): Promise<GeneratedTool[]> {
  const generator = new ToolGenerator();
  const results: GeneratedTool[] = [];
  
  for (const spec of specs) {
    try {
      const result = await generator.generateTool(spec, creatorDid);
      results.push(result);
      console.log(`✅ ${spec.slug}: ${result.deployment.success ? 'DEPLOYED' : 'FAILED'}`);
    } catch (error) {
      console.error(`❌ ${spec.slug}: ${error}`);
      results.push({
        code: '',
        files: new Map(),
        testResults: [],
        deployment: { success: false, error: String(error), logs: [] },
        caasTool: null as any
      });
    }
  }
  
  return results;
}

